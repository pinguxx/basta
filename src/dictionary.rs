use crate::models::LanguageMode;
use rand::prelude::*;

pub fn normalize_char(c: char) -> char {
    match c {
        'á' | 'Á' => 'a',
        'é' | 'É' => 'e',
        'í' | 'Í' => 'i',
        'ó' | 'Ó' => 'o',
        'ú' | 'Ú' | 'ü' | 'Ü' => 'u',
        other => other.to_ascii_lowercase(),
    }
}

pub fn normalize_str(s: &str) -> String {
    s.trim()
        .chars()
        .map(normalize_char)
        .collect::<String>()
        .to_lowercase()
}

pub fn starts_with_letter(word: &str, letter: char) -> bool {
    let norm_word = normalize_str(word);
    let target = normalize_char(letter);
    if let Some(first) = norm_word.chars().next() {
        first == target
    } else {
        false
    }
}

