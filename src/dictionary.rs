use rand::prelude::*;

pub fn normalize_char(c: char) -> char {
    match c.to_ascii_lowercase() {
        'á' => 'a',
        'é' => 'e',
        'í' => 'i',
        'ó' => 'o',
        'ú' | 'ü' => 'u',
        other => other,
    }
}

pub fn normalize_str(s: &str) -> String {
    s.trim()
        .chars()
        .map(normalize_char)
        .collect::<String>()
        .to_lowercase()
}

pub fn starts_with_letter(word: &str, letter: char) -> bool {
    let norm_word = normalize_str(word);
    let target = normalize_char(letter);
    if let Some(first) = norm_word.chars().next() {
        first == target
    } else {
        false
    }
}

pub struct Dictionary;

impl Dictionary {
    pub fn get_category_words(category_id: &str) -> &'static [&'static str] {
        match category_id {
            "nombre" => NOMBRES,
            "apellido" => APELLIDOS,
            "pais_ciudad" => PAISES_CIUDADES,
            "animal" => ANIMALES,
            "fruta_comida" => FRUTAS_COMIDAS,
            "cosa_objeto" => OBJETOS_COSAS,
            "color" => COLORES,
            "flor_planta" => FLORES_PLANTAS,
            _ => &[],
        }
    }

    pub fn is_valid_word(category_id: &str, word: &str, letter: char) -> bool {
        let clean = normalize_str(word);
        if clean.is_empty() || !starts_with_letter(&clean, letter) {
            return false;
        }

        let words = Self::get_category_words(category_id);
        if words.is_empty() {
            // For custom or uncataloged categories, accept any word starting with the right letter
            return clean.len() >= 2;
        }

        words.iter().any(|w| normalize_str(w) == clean)
    }

    pub fn get_bot_word(category_id: &str, letter: char) -> Option<String> {
        let words = Self::get_category_words(category_id);
        let mut matching: Vec<&str> = words
            .iter()
            .copied()
            .filter(|w| starts_with_letter(w, letter))
            .collect();

        if matching.is_empty() {
            None
        } else {
            let mut rng = rand::rng();
            matching.shuffle(&mut rng);
            Some(matching[0].to_string())
        }
    }
}

